[CmdletBinding()]
param()
$ErrorActionPreference='Stop'
$scriptDir=Split-Path -Parent $MyInvocation.MyCommand.Path
$issue=[IO.Path]::GetFullPath((Join-Path $scriptDir '..'))
$repo=[IO.Path]::GetFullPath((Join-Path $issue '..\..'))
$config=Get-Content -Raw (Join-Path $issue 'config.json')|ConvertFrom-Json
$results=Join-Path $issue 'results'
$raw=Join-Path $results 'raw-runner'
$rows=@()

function Get-CanonicalLfHash([string]$Path){
    $text=[IO.File]::ReadAllText($Path)
    $text=$text.Replace("`r`n","`n")
    $bytes=[Text.Encoding]::UTF8.GetBytes($text)
    $sha=[Security.Cryptography.SHA256]::Create()
    try{return ([BitConverter]::ToString($sha.ComputeHash($bytes))).Replace('-','').ToLowerInvariant()}
    finally{$sha.Dispose()}
}

# Reuse all available 72-piece Issue 73 conditions. Its committed manifest has
# a documented pre-existing hash inconsistency for all 250 trials. Preserve
# those source hashes and pin the current trials using checkout-stable LF hashes.
$sourceManifestPath=Join-Path $repo 'experiments/issue-73/results/trial-sources.csv'
$sourceManifest=@(Import-Csv $sourceManifestPath)
foreach($experiment in $config.reused_72_experiments){
    $selected=@($sourceManifest|Where-Object{$_.experiment_id-eq$experiment.id})
    if($selected.Count-ne[int]$experiment.games){throw "Issue 73 row count mismatch: $($experiment.id)"}
    foreach($r in $selected){
        $trial=Join-Path $repo $r.trial_file
        if(-not(Test-Path $trial)){throw "Missing reused trial: $($r.trial_file)"}
        $actual=(Get-FileHash $trial -Algorithm SHA256).Hash.ToLowerInvariant()
        $canonical=Get-CanonicalLfHash $trial
        $rows+=[pscustomobject][ordered]@{source_issue=73;board='7x7-p72';piece_budget=72;experiment_id=$r.experiment_id;search_level=$experiment.search_level;iteration_limit=[int]$r.iteration_limit;game_index=[int]$r.game_index;seed=[long]$r.seed;trial_file=$r.trial_file;trial_sha256=$actual;canonical_trial_sha256=$canonical;source_manifest_trial_sha256=$r.trial_sha256;source_manifest_hash_match=($actual-eq$r.trial_sha256).ToString().ToLowerInvariant()}
    }
}

# Only 84- and 96-piece games are generated by Issue 77.
foreach($experiment in $config.experiments){
    $runnerRows=@(Get-ChildItem $raw -Filter "$($experiment.id)-*.csv" -File|ForEach-Object{Import-Csv $_.FullName})
    if($runnerRows.Count-ne[int]$experiment.games){throw "Runner row count mismatch: $($experiment.id)"}
    foreach($r in $runnerRows){
        $trial=Join-Path $repo $r.trial_file
        if(-not(Test-Path $trial)){throw "Missing trial: $($r.trial_file)"}
        $actual=(Get-FileHash $trial -Algorithm SHA256).Hash.ToLowerInvariant()
        $rows+=[pscustomobject][ordered]@{source_issue=77;board="7x7-p$($experiment.piece_budget)";piece_budget=[int]$experiment.piece_budget;experiment_id=$r.experiment_id;search_level=$experiment.search_level;iteration_limit=[int]$r.iteration_limit;game_index=[int]$r.game_index;seed=[long]$r.seed;trial_file=$r.trial_file;trial_sha256=$actual;canonical_trial_sha256=(Get-CanonicalLfHash $trial);source_manifest_trial_sha256='';source_manifest_hash_match=''}
    }
}

if(@($rows.seed|Sort-Object -Unique).Count-ne$rows.Count){throw 'Duplicate manifest seeds'}
if(@($rows.canonical_trial_sha256|Sort-Object -Unique).Count-ne$rows.Count){throw 'Duplicate canonical manifest trial hashes'}
$mismatches=@($rows|Where-Object{[int]$_.source_issue-eq73-and$_.source_manifest_hash_match-eq'false'})
if($mismatches.Count-ne[int]$config.issue_73_trial_hash_exception.affected_trials){throw "Issue 73 hash-exception count mismatch: $($mismatches.Count)"}
if(@($rows|ForEach-Object{"$($_.board)|$($_.experiment_id)|$($_.game_index)"}|Sort-Object -Unique).Count-ne$rows.Count){throw 'Duplicate manifest game keys'}
$rows|Sort-Object piece_budget,experiment_id,game_index|Export-Csv (Join-Path $results 'trial-sources.csv') -NoTypeInformation -Encoding UTF8
Write-Host "Wrote $($rows.Count) production trial sources ($(@($rows|Where-Object source_issue -eq 73).Count) reused, $(@($rows|Where-Object source_issue -eq 77).Count) new)"
